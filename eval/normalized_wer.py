"""Whisper-normalized WER from the stored per-utterance transcripts (no re-run of
Whisper). Both reference and hypothesis go through Whisper's EnglishTextNormalizer
(WhisperTokenizer.normalize: lower-casing, punctuation removal, number/spelling
canonicalisation, British->American spelling) before a corpus-level jiwer.wer(),
alongside the raw lower-case-only WER used by articulatory-tts.

Writes `wer_whisper_normalized` into each results JSON's metrics (atomic), and
optionally scores extra transcript dumps (articulatory-tts's
sparc_resynth_baselines/gt_transcripts_*.json and eval_*_per_utt.json) so the
floors/comparators are normalized identically. Also emits a markdown summary.
Run under the eval-articulatory-tts venv (transformers + jiwer).
"""
import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import RESULTS_DIR  # noqa: E402


def pairs_from_records(recs):
    refs, hyps = [], []
    for r in recs:
        if isinstance(r, dict):
            ref = next((r[k] for k in r if "ref" in k.lower() and isinstance(r[k], str)), None)
            hyp = next((r[k] for k in r if "hyp" in k.lower() and isinstance(r[k], str)), None)
            if ref is not None and hyp is not None:
                refs.append(ref)
                hyps.append(hyp)
    return refs, hyps


def load_pairs(path):
    if path.endswith(".jsonl"):
        recs = [json.loads(l) for l in open(path) if l.strip()]
    else:
        d = json.load(open(path))
        recs = list(d.values()) if isinstance(d, dict) else d
        if isinstance(d, dict) and not recs or (recs and not isinstance(recs[0], dict)):
            # {"metrics":..., "transcripts": {...}}-style containers
            for k in ("transcripts", "per_utt", "records"):
                if isinstance(d, dict) and k in d:
                    v = d[k]
                    recs = list(v.values()) if isinstance(v, dict) else v
                    break
    return pairs_from_records(recs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results_dir", default=RESULTS_DIR)
    ap.add_argument("--extra", nargs="*", default=[], help="other transcript JSON/JSONL files to score (label = basename)")
    ap.add_argument("--no_write", action="store_true", help="don't add wer_whisper_normalized to the results JSONs")
    ap.add_argument("--summary_md", default=None)
    args = ap.parse_args()

    import jiwer
    from transformers import WhisperTokenizer
    tok = WhisperTokenizer.from_pretrained("openai/whisper-large-v3")
    norm = tok.normalize

    def corpus_wer(refs, hyps, normalize):
        if normalize:
            refs = [norm(r) for r in refs]
            hyps = [norm(h) for h in hyps]
        keep = [(r, h) for r, h in zip(refs, hyps) if r.strip()]
        if not keep:
            return None, 0
        return jiwer.wer([r for r, _ in keep], [h for _, h in keep]), len(keep)

    rows = []
    paths = sorted(glob.glob(os.path.join(args.results_dir, "eval_*.json")))
    paths = [p for p in paths if not p.endswith(("_per_utt.json", "_emotion.json"))]
    for p in paths:
        partial = p + ".partial.jsonl"
        if not os.path.exists(partial):
            continue
        refs, hyps = load_pairs(partial)
        raw, n = corpus_wer(refs, hyps, False)
        nw, nn = corpus_wer(refs, hyps, True)
        tag = os.path.basename(p)[5:-5]
        rows.append((tag, n, raw, nw))
        if not args.no_write:
            d = json.load(open(p))
            d.setdefault("metrics", {})["wer_whisper_normalized"] = {"mean": nw, "ci95": None, "n": nn}
            with open(p + ".tmp", "w") as f:
                json.dump(d, f, indent=2)
            os.replace(p + ".tmp", p)
    for path in args.extra:
        if not os.path.exists(path):
            print(f"(missing: {path})")
            continue
        refs, hyps = load_pairs(path)
        if not refs:
            print(f"(no ref/hyp pairs found in {path})")
            continue
        raw, n = corpus_wer(refs, hyps, False)
        nw, _ = corpus_wer(refs, hyps, True)
        label = os.path.relpath(path, "/data/user_data/xoy")
        rows.append((label, n, raw, nw))

    lines = ["| system / set | n | WER (lower-case only) | WER (Whisper-normalized) |", "|---|---|---|---|"]
    for tag, n, raw, nw in rows:
        lines.append(f"| {tag} | {n} | {raw * 100:.2f}% | {nw * 100:.2f}% |")
    table = "\n".join(lines)
    print(table)
    if args.summary_md:
        os.makedirs(os.path.dirname(os.path.abspath(args.summary_md)), exist_ok=True)
        with open(args.summary_md, "w") as f:
            f.write("# WER: raw vs Whisper-normalized (generated by eval/normalized_wer.py)\n\n" + table + "\n")
        print(f"wrote {args.summary_md}")


if __name__ == "__main__":
    main()
